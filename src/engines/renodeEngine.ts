import { PeripheralSpec } from '../domain/types.js';

export function generateRenodeDigitalTwin(
  boardName: string,
  cpuModel: string,
  peripherals: PeripheralSpec[],
  firmwarePath: string
): { repl: string; resc: string } {
  const replBlocks: string[] = [
    `// ============================================================================`,
    `// Auto-generated by UEA (Universal Emulation Anything)`,
    `// Platform Description (.repl) for ${boardName}`,
    `// ============================================================================`,
    ``,
    `cpu: CPU.CortexM @ sysbus`,
    `    cpuType: "${cpuModel || 'cortex-m4'}"`,
    `    nvic: nvic`,
    ``,
    `nvic: IRQControllers.NVIC @ sysbus 0xE000E000`,
    `    priorityMask: 0xF0`,
    ``,
    `flash: Memory.MappedMemory @ sysbus 0x08000000`,
    `    size: 0x100000`,
    ``,
    `sram: Memory.MappedMemory @ sysbus 0x20000000`,
    `    size: 0x20000`,
    ``,
  ];

  for (const p of peripherals) {
    const baseHex = '0x' + p.baseAddress.toString(16).toUpperCase();
    replBlocks.push(`${p.name.toLowerCase()}: Python.PythonPeripheral @ sysbus ${baseHex}`);
    replBlocks.push(`    size: 0x${p.addressBlockSize.toString(16).toUpperCase()}`);
    replBlocks.push(`    initable: true`);
    replBlocks.push(`    script: "scripts/${p.name.toLowerCase()}_stub.py"`);
    replBlocks.push(``);
  }

  const resc = `:name: ${boardName} Virtual Emulation Harness
:description: Cycle-accurate Renode execution script synthesized by UEA

using sysbus
mach create "${boardName.toLowerCase()}"

machine LoadPlatformDescription @${boardName.toLowerCase()}.repl

sysbus LoadBinary @${firmwarePath} 0x08000000
cpu PC 0x08000000

echo "UEA Digital Twin for ${boardName} successfully initialized."
echo "Starting virtual simulation clock..."
start
`;

  return { repl: replBlocks.join('\n'), resc };
}
